function [C, D] = f16_aero_nasa(alpha, beta, el, ail, rdr)
% F-16 aerodynamic coefficients from the NASA TP-1538 wind-tunnel data,
% in the tabulated form given in Stevens & Lewis, "Aircraft Control and
% Simulation" (Appendix A). Data: Nguyen et al., NASA TP-1538 (1979).
%
% Inputs (all in DEGREES, Stevens & Lewis sign conventions):
%   alpha  angle of attack, valid table range -10 to 45 deg
%   beta   sideslip,        valid table range -30 to 30 deg
%   el     elevator, +TE down,         -25 to 25 deg
%   ail    aileron (Stevens sign: + gives a LEFT roll moment), -21.5 to 21.5 deg
%   rdr    rudder, + gives a nose-LEFT yaw moment,  -30 to 30 deg
% Outputs:
%   C = struct with body-axis static coefficients Cx Cy Cz Cl Cm Cn
%       (Cl and Cn include the aileron and rudder effects)
%   D = 9 damping derivatives [CXq CYr CYp CZq Clr Clp Cmq Cnr Cnp]
%       (applied in f16_dynamics_nasa with cbar/(2V) and b/(2V) scaling)
% Tables are interpolated linearly and extrapolated linearly beyond their
% edges, as in the original Stevens & Lewis Fortran routines. No toolbox needed.

persistent G
if isempty(G), G = build_tables(); end

C.Cx = lin2(G.cx, G.A, G.E, alpha, el);
C.Cz = lin1(G.cz, G.A, alpha)*(1 - (beta/57.3)^2) - 0.19*(el/25);
C.Cm = lin2(G.cm, G.A, G.E, alpha, el);
C.Cy = -0.02*beta + 0.021*(ail/20) + 0.086*(rdr/30);
C.Cl = sign(beta)*lin2(G.cl, G.A, G.BA, alpha, abs(beta)) ...
       + lin2(G.dlda, G.A, G.B, alpha, beta)*(ail/20) + lin2(G.dldr, G.A, G.B, alpha, beta)*(rdr/30);
C.Cn = sign(beta)*lin2(G.cn, G.A, G.BA, alpha, abs(beta)) ...
       + lin2(G.dnda, G.A, G.B, alpha, beta)*(ail/20) + lin2(G.dndr, G.A, G.B, alpha, beta)*(rdr/30);
D = zeros(9,1);
for i = 1:9, D(i) = lin1(G.damp(:,i), G.A, alpha); end
end

