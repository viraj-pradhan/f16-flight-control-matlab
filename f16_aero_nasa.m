function y = lin1(t, X, x)
% 1-D linear interpolation on uniform breakpoints X, linear extrapolation
[k, f] = cell_index(X, x);
y = t(k) + f*(t(k+1) - t(k));
end

function y = lin2(T, X, Y, x, yv)
% 2-D bilinear interpolation, rows = X, columns = Y, linear extrapolation
[i, fx] = cell_index(X, x);
[j, fy] = cell_index(Y, yv);
a = T(i,j)   + fx*(T(i+1,j)   - T(i,j));
b = T(i,j+1) + fx*(T(i+1,j+1) - T(i,j+1));
y = a + fy*(b - a);
end

function [k, f] = cell_index(X, x)
s = (x - X(1))/(X(2) - X(1)) + 1;
k = min(max(floor(s), 1), numel(X) - 1);
f = s - k;
end